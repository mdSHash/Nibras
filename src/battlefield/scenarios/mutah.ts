/**
 * غَزْوَةُ مُؤْتَةَ — الإِحْدَى الحُسْنَيَيْنِ
 * Battle of Mu'tah — One of the Two Beautiful Outcomes
 *
 * Jumada al-Ula 8 AH / ~September 629 CE — fourteen months after
 * Hudaybiyya, sixteen before Fath Makkah. Mu'tah, on the rocky Moab
 * plateau (~820 m elevation) ~10 km south of al-Karak in modern Jordan,
 * a narrow wadi between two heights with the village of al-Musharif
 * to the north. The supply axis ran from Madinah via Wadi al-Qura
 * along the King's Highway to Ma'an; the enemy was massed at Ma'ab
 * in the Balqa.
 *
 * The casus belli was unprecedented in Prophetic history: Shurahbil
 * ibn 'Amr al-Ghassani, the Ghassanid governor of the Balqa under
 * Heraclius, had killed al-Harith ibn 'Umayr al-Azdi — the Prophet's
 * envoy carrying a letter to the ruler of Bostra. The killing of an
 * envoy under no other Arab convention.
 *
 * The Prophet ﷺ assembled 3,000 — the largest detachment he had yet
 * dispatched — and tied a white banner for Zayd ibn Haritha, his
 * mawla, the only Companion named in the Qur'an. He named the
 * succession at the banner-tying (Sahih al-Bukhari 4261, Ibn 'Umar):
 * «إِنْ قُتِلَ زَيْدٌ فَجَعْفَرٌ، وَإِنْ قُتِلَ جَعْفَرٌ فَعَبْدُ اللَّهِ
 * بنُ رَوَاحَةَ». Three commanders by name, in order, the prophecy
 * itself a hovering presence over the army.
 *
 * The army marched the King's Highway. At Ma'an in southern Sham
 * came word that Heraclius had massed at Ma'ab with what tradition
 * calls 200,000 (sources vary, modern scholarship suspects far
 * smaller — perhaps no large Roman field army at all, only Ghassanid
 * clients with a small Roman cadre under Theodore the Patrician;
 * Kaegi 1992). They paused two nights for shura. 'Abdullah ibn
 * Rawahah — the Prophet's poet — rose to exhort:
 * «يَا قَوْمِ، وَاللَّهِ إِنَّ الَّتِي تَكْرَهُونَ لَلَّتِي خَرَجْتُمْ
 * تَطْلُبُونَ — الشَّهَادَة... إِنَّمَا هِيَ إِحْدَى الحُسْنَيَيْنِ:
 * إِمَّا ظُهُورٌ وَإِمَّا شَهَادَةٌ». They said: «صَدَقَ ابنُ رَوَاحَةَ».
 *
 * First contact came at al-Musharif. The Muslims fell back south
 * into a wadi between two heights — ground that denied envelopment.
 * Zayd took the white banner first, fought, and fell to the Romans'
 * spears (Bukhari 4262, Anas). The Prophet ﷺ in Madinah ascended the
 * minbar and announced the death in that very hour, his eyes
 * shedding tears.
 *
 * Ja'far ibn Abi Talib — cousin of the Prophet ﷺ, brother of 'Ali,
 * leader of the Abyssinian emigration — took the banner. When the
 * press of battle closed on him he dismounted from his chestnut
 * mare and hamstrung her, then chanted his rajaz: «يَا حَبَّذَا
 * الجَنَّةُ وَاقْتِرَابُهَا — طَيِّبَةً وَبَارِدًا شَرَابُهَا». His
 * right hand was severed; he held the banner with his left. His
 * left was severed; he embraced it with his stumps until killed.
 * Ibn 'Umar (Bukhari 4260, 4261): «فَالْتَمَسْنَاهُ فِي القَتْلَى،
 * فَوَجَدْنَا فِيمَا أَقْبَلَ مِنْ جَسَدِهِ بِضْعًا وَتِسْعِينَ بَيْنَ
 * طَعْنَةٍ وَرَمْيَةٍ». Allah gave him in place of his arms two wings
 * with which he flies in Paradise — Dhu al-Janahayn.
 *
 * 'Abdullah ibn Rawahah took the banner and hesitated for a moment.
 * He rebuked his soul: «أَقْسَمْتُ يَا نَفْسُ لَتَنْزِلِنَّهْ /
 * لَتَنْزِلِنَّ أَوْ لَتُكْرَهِنَّهْ / إِنْ أَجْلَبَ النَّاسُ وَشَدُّوا
 * الرَّنَّهْ / مَا لِي أَرَاكِ تَكْرَهِينَ الجَنَّهْ». He cast aside
 * a piece of meat he had been eating — «وَأَنْتَ فِي الدُّنْيَا؟!»
 * — dismounted and fought until killed. The banner was caught
 * before it touched the ground by Thabit ibn Aqram al-Ansari.
 *
 * Thabit offered the banner to Khalid ibn al-Walid, who had
 * embraced Islam only months before: «أَنْتَ أَحَقُّ بِهَا مِنِّي».
 * Thabit replied: «مَا أَخَذْتُهَا إِلَّا لَكَ». Khalid accepted by
 * acclamation. Bukhari 4265 records his own testimony: «لَقَدِ
 * انْقَطَعَتْ فِي يَدِي يَوْمَ مُؤْتَةَ تِسْعَةُ أَسْيَافٍ، فَمَا
 * بَقِيَ فِي يَدِي إِلَّا صَفِيحَةٌ يَمَانِيَةٌ». The Prophet ﷺ —
 * still on the minbar, narrating the banner's passage in real time
 * — named him: «أَخَذَ الرَّايَةَ سَيْفٌ مِنْ سُيُوفِ اللَّهِ، حَتَّى
 * فَتَحَ اللَّهُ عَلَيْهِمْ» (Bukhari 4262). The title Sayfullah
 * — the Sword of Allah — was born on this day.
 *
 * By night Khalid set the stratagem that broke the Roman cohesion
 * (Ibn Hisham; al-Waqidi; Ibn Kathir): four-fold rotation. Right
 * wing swapped with left. Vanguard with rear. Fresh banners raised
 * across the front. At dawn the Romans saw what looked like a
 * fresh army arrived overnight — they hesitated, did not advance,
 * did not pursue. Khalid disengaged and extracted the army intact
 * southward. Only twelve Muslims fell from three thousand.
 *
 * At Madinah the children met them throwing dust and crying:
 * «يَا فُرَّارَ، فَرَرْتُمْ فِي سَبِيلِ اللَّهِ!». The Prophet ﷺ
 * replied (Ibn Hisham): «لَيْسُوا بِالفُرَّارِ، وَلَكِنَّهُمُ
 * الكُرَّارُ إِنْ شَاءَ اللَّهُ» — the foundational fiqh distinction
 * between forbidden firar al-zahf and licit al-tahayyuz, the
 * tactical withdrawal that lives to fight again.
 *
 * Mu'tah opened the Levantine theatre, prefigured Tabuk, and seven
 * years later under Abu Bakr and 'Umar, Khalid's Sayfullah title and
 * the Mu'tah veterans would carry the conquest of Sham — Damascus,
 * Yarmouk, Jerusalem. Ja'far at-Tayyar, Zayd, and Ibn Rawahah lie
 * to this day at the shrine south of al-Karak.
 *
 * Sources: al-Bukhari, Sahih (Kitab al-Maghazi: bab Ghazwat Mu'tah —
 *          4260–4262, 4265); Muslim, Sahih; Ibn Hisham, as-Sirah
 *          an-Nabawiyyah (Ghazwat Mu'tah); al-Waqidi, Kitab al-Maghazi;
 *          at-Tabari, Tarikh year 8 AH; Ibn Kathir, al-Bidayah
 *          wa'n-Nihayah vol. 4; modern overview: W. Kaegi, Byzantium
 *          and the Early Islamic Conquests (1992).
 */
