/**
 * Writes docs/territories/MAP_CHANGES.md: the list for approving the content snapshot, period by period.
 * For every date the app can select, who the old map (the baseline in tests/baseline/content.json until
 * it is re-recorded; afterwards from git, commit 1c9cb76) showed against what the new map shows.
 * Usage: npx tsx scripts/territories/reportMapChanges.ts
 */
import { execSync } from 'node:child_process';
import fs from 'node:fs';
import type { GeneratedTerritoryMap } from '../../shared/contentSchema';
import { NO_EVENT_YEAR, periodForYear } from '../../shared/territoryMap';

interface OldYear { id: string; groups: { id: string; name: string; specificName: string | null; polygons: number }[] }
const old = (JSON.parse(execSync('git show 1c9cb76:tests/baseline/content.json', { maxBuffer: 1e9 }).toString()) as { territories: OldYear[] }).territories;
const map = JSON.parse(fs.readFileSync('src/generated/territories.json', 'utf8')) as GeneratedTerritoryMap;
const events = fs.readdirSync('content/events').map(f => JSON.parse(fs.readFileSync(`content/events/${f}`, 'utf8')) as { id: string; title: string; date: { sortKey: number } });
const holders = (JSON.parse(fs.readFileSync('content/territories/holders.json', 'utf8')) as { holders: { id: string; nameAr: string }[] }).holders;
const holderName = new Map(holders.map(h => [h.id, h.nameAr]));
const titles = new Map(events.map(e => [e.id, e.title]));

const years = [...new Set([NO_EVENT_YEAR, ...events.map(e => e.date.sortKey)])].sort((a, b) => a - b);
const oldAt = (year: number): string => [...new Set((old.find(o => o.id === String(year))?.groups ?? []).map(g => g.name))].join('، ');

const KIND: Record<string, string> = { state: 'حكم', city: 'مدينة', client: 'حليف', treaty: 'صلح', contested: 'نزاع', tribal: 'قبائل' };
const holdingsAt = (period: GeneratedTerritoryMap['periods'][number]): Map<string, string> =>
  new Map(period.labels.filter(l => l.level >= 3).map(l => [l.text, `${holderName.get(l.holder)} (${KIND[l.kind]})`]));

// Regions per holder in the first period; after that only what the period changes.
const changes = (period: GeneratedTerritoryMap['periods'][number], before: Map<string, string> | undefined): string => {
  const now = holdingsAt(period);
  const groups = new Map<string, string[]>();
  for (const [region, holding] of now) if (before?.get(region) !== holding) groups.set(holding, [...(groups.get(holding) ?? []), region]);
  const moved = [...groups.entries()].map(([holding, regions]) => `**${holding}:** ${regions.join('، ')}`);
  const renamed = period.labels.filter(l => l.level <= 2).map(l => l.text);
  return moved.join('<br>') || `(names only: ${renamed.join('، ')})`;
};

let out = `# What the territory map shows, old and new

Generated by \`scripts/territories/reportMapChanges.ts\`; do not edit by hand. The list for approving the
content snapshot (\`tests/baseline/content.json\`, \`territories\`). **Every date's entry changes**: the
old map was 40 Voronoi land cells in 11 periods, the new one is 62 drawn regions in ${map.periods.length} periods, so the geometry never
matches. Each row is a period of the new map: the date it starts, the events that cause it, the old
map's holders at that date (only when they differ from the row above), and what the new map changes.

| Starts | Caused by | Old map at that date | New map: what changes |
| --- | --- | --- | --- |
`;
let lastOld = '';
let previous: Map<string, string> | undefined;
for (const period of map.periods) {
  const inside = years.filter(y => periodForYear(map, y) === period);
  const start = period.from === 0 ? 'before 571' : String(period.from);
  const causes = period.causes.map(id => titles.get(id) ?? id).join('، ') || '(no event; see the ledger)';
  const oldText = inside.length ? oldAt(inside[0]) : '';
  const shownOld = !inside.length ? '(no event in this period)' : oldText === lastOld ? '(same)' : oldText;
  if (inside.length) lastOld = oldText;
  out += `| ${start} | ${causes} | ${shownOld} | ${changes(period, previous)} |\n`;
  previous = holdingsAt(period);
}
fs.writeFileSync('docs/territories/MAP_CHANGES.md', out);
console.log(`${map.periods.length} periods, ${years.length} dates the app can select`);
