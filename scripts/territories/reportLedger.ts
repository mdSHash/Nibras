/**
 * Writes docs/territories/UNCERTAIN.md from the ledger: every row that is not proven, and every
 * row with no quoted source yet, for Mostafa to review. Usage: npx tsx scripts/territories/reportLedger.ts
 */
import fs from 'node:fs';
import path from 'node:path';

const LEDGER = 'docs/territories/ledger';

interface Row { r: string | string[]; at: number; ev?: string; h: string; k: string; c: string; cite?: { b: string; p: number; q: string; printed?: string }[]; n?: string }

const regions = new Map((JSON.parse(fs.readFileSync('docs/territories/regions-draft.json', 'utf8')) as { regions: { id: string; nameAr: string }[] }).regions.map(r => [r.id, r.nameAr]));
const rows = fs.readdirSync(LEDGER).sort().flatMap(f => JSON.parse(fs.readFileSync(path.join(LEDGER, f), 'utf8')) as Row[]);
const names = (r: Row): string => [r.r].flat().map(id => regions.get(id) ?? id).join('، ');
const when = (r: Row): string => (r.at === 0 ? 'before 571' : String(r.at));
const line = (r: Row): string => `| ${names(r)} | ${when(r)} | ${r.h} (${r.k}) | ${(r.n ?? '').replace(/\|/g, '/')} |`;
const head = '| Region | From | Held by | Why it is not settled |\n| --- | --- | --- | --- |';

const uncertain = rows.filter(r => r.c === 'uncertain');
const likely = rows.filter(r => r.c === 'likely');
const proven = rows.filter(r => r.c === 'proven');
const noQuote = rows.filter(r => !r.cite?.length);

const out = `# Uncertain territory rows

Generated by \`scripts/territories/reportLedger.ts\` from \`docs/territories/ledger/\`; do not edit by hand.

${rows.length} rows: **${proven.length} proven**, **${likely.length} likely**, **${uncertain.length} uncertain**. ${rows.length - noQuote.length} rows carry a quoted source; ${noQuote.length} do not yet.

- **Proven**: a source read here states it, and the phrase is checked against the page.
- **Likely**: the sources imply it, or state part of it.
- **Uncertain**: drawn from context or an estimate. Your call.

These rows are about who held a region and from when. **Every border line between regions is drawn, not read**: no chronicle gives a line, so all shapes follow towns, coasts, rivers, mountains and desert edges.

## Uncertain (${uncertain.length})

${head}
${uncertain.map(line).join('\n')}

## Likely (${likely.length})

${head}
${likely.map(line).join('\n')}

## No quoted source yet (${noQuote.length})

${head}
${noQuote.map(line).join('\n')}
`;
fs.writeFileSync('docs/territories/UNCERTAIN.md', out);
console.log(`${rows.length} rows: ${proven.length} proven, ${likely.length} likely, ${uncertain.length} uncertain, ${noQuote.length} without a quote`);
