/**
 * The field reference in docs/CONTENT_GUIDE.md, generated from the Zod schemas
 * in shared/contentSchema.ts (their `.describe()` texts), so the guide never
 * drifts from what the content build accepts. Written by
 * scripts/docs/content-guide.ts (npm run docs:content); tests/contentGuide.test.ts
 * fails when the guide is out of date.
 */
import { z } from 'zod';
import {
  categorySchema,
  citySchema,
  eraSchema,
  eventSchema,
  personSchema,
  quranPassageSchema,
  quranVersesSchema,
  territoryControlSchema,
  territoryRegionsSchema,
} from '../../shared/contentSchema';

export const START_MARKER = '<!-- field-reference:start (generated by npm run docs:content; do not edit by hand) -->';
export const END_MARKER = '<!-- field-reference:end -->';

const SECTIONS: { title: string; file: string; schema: z.ZodType; list?: boolean }[] = [
  { title: 'Event', file: 'content/events/<id>.json', schema: eventSchema },
  { title: 'Person', file: 'content/people/<id>.json', schema: personSchema },
  { title: 'City', file: 'content/cities/<id>.json', schema: citySchema },
  { title: 'Era', file: 'content/eras.json', schema: eraSchema, list: true },
  { title: 'Category', file: 'content/categories.json', schema: categorySchema, list: true },
  { title: "Qur'an passage", file: 'content/quran/passages.json', schema: quranPassageSchema, list: true },
  { title: "Qur'an verses", file: 'content/quran/verses.json', schema: quranVersesSchema },
  { title: 'Territory regions', file: 'content/territories/regions.json', schema: territoryRegionsSchema },
  { title: 'Territory control', file: 'content/territories/control.json', schema: territoryControlSchema },
];

interface JsonSchema {
  type?: string;
  description?: string;
  properties?: Record<string, JsonSchema>;
  required?: string[];
  items?: JsonSchema | false;
  prefixItems?: JsonSchema[];
  additionalProperties?: JsonSchema | boolean;
  enum?: (string | number)[];
  const?: unknown;
  pattern?: string;
  minLength?: number;
  minimum?: number;
  maximum?: number;
  exclusiveMinimum?: number;
  minItems?: number;
  anyOf?: JsonSchema[];
  oneOf?: JsonSchema[];
  allOf?: JsonSchema[];
}

// The id patterns of shared/contentSchema.ts, by name.
const PATTERN_NAMES: Record<string, string> = {
  '^[a-z0-9]+(-[a-z0-9]+)*$': 'slug (`a-z`, `0-9`, `-`)',
  '^[^\\s/\\\\:*?"<>|.][^\\s/\\\\:*?"<>|]*$': 'id usable as a file name (no spaces)',
  '^[a-z0-9_]+$': 'id (`a-z`, `0-9`, `_`)',
  '^#[0-9a-f]{6}$': 'colour `#rrggbb`',
  '^\\d{4}-\\d{2}-\\d{2}$': 'date `YYYY-MM-DD`',
};

const SAFE_INT = Number.MAX_SAFE_INTEGER;

function range(s: JsonSchema): string {
  // An exclusive minimum reads as "≥ n + 1" for integers, "> n" otherwise.
  const exclusive = s.exclusiveMinimum !== undefined && s.type !== 'integer';
  const low = s.exclusiveMinimum !== undefined ? s.exclusiveMinimum + (exclusive ? 0 : 1) : s.minimum;
  const high = s.maximum;
  const hasLow = low !== undefined && low !== -SAFE_INT;
  const hasHigh = high !== undefined && high !== SAFE_INT;
  if (hasLow && hasHigh) return ` ${exclusive ? '>' : ''}${low}–${high}`;
  if (hasLow) return ` ${exclusive ? '>' : '≥'} ${low}`;
  if (hasHigh) return ` ≤ ${high}`;
  return '';
}

function typeLabel(s: JsonSchema): string {
  // Unions and nullable fields have no rendering yet: fail rather than document them wrongly.
  if (s.anyOf || s.oneOf || s.allOf)
    throw new Error('scripts/docs/fieldReference.ts: add a rendering for union (anyOf/oneOf/allOf) fields');
  if (s.const !== undefined) return `\`${JSON.stringify(s.const)}\``;
  if (s.enum) return `one of ${s.enum.map(v => `\`${v}\``).join(', ')}`;
  switch (s.type) {
    case 'string':
      if (s.pattern) return PATTERN_NAMES[s.pattern] ?? `text matching \`${s.pattern}\``;
      return s.minLength ? 'text' : 'text (may be empty)';
    case 'integer':
      return `integer${range(s)}`;
    case 'number':
      return `number${range(s)}`;
    case 'boolean':
      return 'true / false';
    case 'array':
      if (s.prefixItems) return `pair \`[${s.prefixItems.map(p => p.type).join(', ')}]\``;
      if (s.items && typeof s.items === 'object') {
        const item = s.items.type === 'object' ? 'objects' : typeLabel(s.items);
        return `list of ${item}${s.minItems ? ` (at least ${s.minItems})` : ''}`;
      }
      return 'list';
    case 'object':
      if (!s.properties && s.additionalProperties && typeof s.additionalProperties === 'object')
        return `map of ${typeLabel(s.additionalProperties)}`;
      return 'object';
    default:
      return s.type ?? 'any';
  }
}

const cell = (text: string): string => text.replace(/\|/g, '\\|').replace(/\n/g, ' ');

function rows(s: JsonSchema, prefix: string, out: string[]): void {
  const required = new Set(s.required ?? []);
  for (const [key, prop] of Object.entries(s.properties ?? {})) {
    const path = prefix ? `${prefix}.${key}` : key;
    out.push(`| \`${path}\` | ${cell(typeLabel(prop))} | ${required.has(key) ? 'yes' : ''} | ${cell(prop.description ?? '')} |`);
    if (prop.type === 'object' && prop.properties) rows(prop, path, out);
    if (prop.type === 'array' && prop.items && typeof prop.items === 'object' && prop.items.type === 'object')
      rows(prop.items, `${path}[]`, out);
  }
}

/** The generated section, markers included. */
export function renderFieldReference(): string {
  const out: string[] = [START_MARKER, ''];
  for (const section of SECTIONS) {
    const json = z.toJSONSchema(section.schema, { io: 'input' }) as JsonSchema;
    out.push(`### ${section.title}: \`${section.file}\``, '');
    if (section.list) out.push('A list of objects, each with these fields.', '');
    out.push('| Field | Type | Required | Description |', '| --- | --- | --- | --- |');
    rows(json, '', out);
    out.push('');
  }
  out.push(END_MARKER);
  return out.join('\n');
}

/** The guide with its generated section replaced. */
export function spliceFieldReference(guide: string): string {
  const start = guide.indexOf(START_MARKER);
  const end = guide.indexOf(END_MARKER);
  if (start < 0 || end < start) throw new Error('docs/CONTENT_GUIDE.md: field-reference markers not found');
  return guide.slice(0, start) + renderFieldReference() + guide.slice(end + END_MARKER.length);
}
