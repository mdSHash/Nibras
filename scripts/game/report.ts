/**
 * npm run game:report — builds the daily challenge's dataset and writes the
 * content report for Mostafa to docs/phase5/data-report.md: exclusions,
 * skipped events, clues dropped for leaking the name, facts awaiting a source,
 * the difficulty tier of every item, and pool sizes per mode, level and tier.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { checkContent, readContent } from '../content/store';
import { ROOT } from '../baseline/lib';
import { stripDiacritics } from '../../shared/arabic';
import { buildGameData, type GameReport } from './build';
import { FACT_LABELS, FACT_TITLES, type GameData, type Tier } from '../../shared/gameData';

export const LEVEL_TIERS: Record<'easy' | 'mid' | 'hard', Tier[]> = { easy: [1], mid: [2], hard: [3, 2] };

/** Items per mode, as the engine will pick its answers from them. */
export function modePools(data: GameData): Record<string, { id: string; tier: Tier; label: string }[]> {
  const ev = (e: GameData['events'][number]) => ({ id: e.id, tier: e.tier, label: stripDiacritics(e.title) });
  return {
    who: data.people.map((p) => ({ id: p.id, tier: p.tier, label: p.name })),
    battle: data.events.filter((e) => e.battle && e.clues.length >= 2).map(ev),
    place: data.cities.filter((c) => c.clues.length >= 2).map((c) => ({ id: c.id, tier: c.tier, label: c.name })),
    time: data.events.map(ev),
    number: data.events.filter((e) => e.army || e.enemyArmy).map(ev),
    full: data.events.filter((e) => e.excerpt.length > 0).map(ev),
  };
}

export function render(r: GameReport): string {
  const pools = modePools(r.data);
  const lines: string[] = [
    '# Daily challenge: data report',
    '',
    'Generated by `npm run game:report` from `content/` and `content/game/`. Do not edit by hand.',
    '',
    '## Pool sizes (mode × tier, and what each level draws from)',
    '',
    '| Mode | Tier 1 | Tier 2 | Tier 3 | easy | mid | hard |',
    '| --- | --- | --- | --- | --- | --- | --- |',
  ];
  const warnings: string[] = [];
  for (const [mode, items] of Object.entries(pools)) {
    const count = (tiers: Tier[]) => items.filter((i) => tiers.includes(i.tier)).length;
    const levels = Object.entries(LEVEL_TIERS).map(([level, tiers]) => {
      const n = count(tiers);
      if (n < 4) warnings.push(`${mode} / ${level}: ${n} items (under 4; borrows from the nearest tier)`);
      return n;
    });
    lines.push(`| ${mode} | ${count([1])} | ${count([2])} | ${count([3])} | ${levels.join(' | ')} |`);
  }
  lines.push('', '### Warnings', '', ...(warnings.length ? warnings.map((w) => `- ${w}`) : ['- None.']));
  const section = (title: string, items: string[]) => lines.push('', `## ${title} (${items.length})`, '', ...(items.length ? items.map((i) => `- ${i}`) : ['- None.']));
  lines.push('', '## «من أكون؟» facts (as the tiles will show them)', '');
  lines.push(`| الصحابي | ${FACT_TITLES.islam} | ${FACT_TITLES.migration} | ${FACT_TITLES.knownFor} | ${FACT_TITLES.lastEra} | ${FACT_TITLES.deathPlace} | سنة الوفاة |`);
  lines.push('| --- | --- | --- | --- | --- | --- | --- |');
  for (const p of r.data.people) {
    lines.push(
      `| ${p.name} | ${FACT_LABELS.islam[p.islam]} | ${FACT_LABELS.migration[p.migration]} | ${FACT_LABELS.knownFor[p.knownFor]} | ` +
        `${FACT_LABELS.lastEra[p.lastEra]} | ${FACT_LABELS.deathPlace[p.deathPlace]} | ${p.deathYear}${p.disputed ? ' (وقيل غيرها)' : ''} |`,
    );
  }
  section('Companion facts awaiting a source', r.pending);
  section('Excluded', r.excluded);
  section('Skipped (no Hijri year)', r.skipped);
  section('Clues dropped', r.droppedClues);
  for (const kind of ['events', 'people', 'cities'] as const) {
    const items = r.data[kind] as { id: string; tier: Tier; title?: string; name?: string }[];
    const label = (i: (typeof items)[number]): string => i.name ?? i.title ?? i.id;
    lines.push('', `## Tiers: ${kind}`, '');
    for (const t of [1, 2, 3] as Tier[]) {
      const ids = items.filter((i) => i.tier === t).map((i) => stripDiacritics(label(i)));
      lines.push(`- **Tier ${t}** (${ids.length}): ${ids.join('، ') || '—'}`);
    }
  }
  return `${lines.join('\n')}\n`;
}

const isMain = process.argv[1]?.replace(/\\/g, '/').endsWith('scripts/game/report.ts');
if (isMain) {
  const { raw, issues: readIssues } = readContent(join(ROOT, 'content'));
  const { content, issues } = checkContent(raw);
  const built = buildGameData(content, join(ROOT, 'content', 'game'));
  const all = [...readIssues, ...issues, ...built.issues];
  for (const i of all) console.error(`  content/${i.file}: ${i.message}`);
  if (all.length || !built.report) process.exit(1);
  mkdirSync(join(ROOT, 'docs', 'phase5'), { recursive: true });
  writeFileSync(join(ROOT, 'docs', 'phase5', 'data-report.md'), render(built.report));
  const d = built.report.data;
  console.log(
    `Game data: ${d.events.length} events, ${d.people.length} people, ${d.cities.length} cities; ` +
      `${built.report.excluded.length} excluded, ${built.report.skipped.length} skipped, ` +
      `${built.report.droppedClues.length} clues dropped, ${built.report.pending.length} facts awaiting a source. ` +
      'Wrote docs/phase5/data-report.md.',
  );
}
