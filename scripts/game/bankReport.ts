/**
 * The question bank as a review list for Mostafa (docs/phase5/question-bank.md),
 * written by `npm run game:report`.
 */
import { stripDiacritics } from '../../shared/arabic';
import type { GameData } from '../../shared/gameData';

const MODE_NAMES: Record<string, string> = {
  who: 'من أكون؟', battle: 'المعركة', place: 'المكان', year: 'السنة', number: 'الرقم',
  title: 'لقب مين؟', order: 'رتّب الأحداث', there: 'مين كان هناك؟', quote: 'مين قال؟',
};
const LEVELS = [['easy', 'لسه ببتدي'], ['mid', 'عارف شوية'], ['hard', 'أستاذ فيها']] as const;

export function renderBank(data: GameData): string {
  const name = (answer: string): string => {
    const id = answer.replace(/:(army|enemyArmy)$/, '');
    const found = data.people.find((x) => x.id === id)?.name ?? data.events.find((x) => x.id === id)?.title ?? data.cities.find((x) => x.id === id)?.name;
    return stripDiacritics(found ?? id);
  };
  const modes = [...new Set(data.questions.map((q) => q.mode))];
  const lines = [
    '# Daily challenge: question bank',
    '',
    'Generated by `npm run game:report` from `content/game/questions/`. Do not edit by hand.',
    'Each clue rests on a sentence in Nibras (the `sources` in the JSON); the build checks every one.',
    '',
    '| الوضع | لسه ببتدي | عارف شوية | أستاذ فيها |',
    '| --- | --- | --- | --- |',
  ];
  for (const mode of modes) {
    const n = (level: string): number => data.questions.filter((q) => q.mode === mode && q.level === level).length;
    lines.push(`| ${MODE_NAMES[mode] ?? mode} | ${n('easy')} | ${n('mid')} | ${n('hard')} |`);
  }
  for (const mode of modes) {
    lines.push('', `## ${MODE_NAMES[mode] ?? mode}`);
    for (const [level, levelName] of LEVELS) {
      const qs = data.questions.filter((q) => q.mode === mode && q.level === level);
      if (!qs.length) continue;
      lines.push('', `### ${levelName}`);
      for (const q of qs) {
        lines.push('', `**${name(q.answer)}** (\`${q.id}\`)${q.prompt ? `: ${q.prompt}` : ''}`, '');
        q.clues.forEach((c, i) => lines.push(`${i + 1}. ${c.text}`));
      }
    }
  }
  return `${lines.join('\n')}\n`;
}
